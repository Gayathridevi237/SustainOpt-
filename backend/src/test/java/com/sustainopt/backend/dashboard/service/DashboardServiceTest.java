package com.sustainopt.backend.dashboard.service;

import com.sustainopt.backend.auth.entity.User;
import com.sustainopt.backend.auth.repository.UserRepository;
import com.sustainopt.backend.common.util.SecurityUtils;
import com.sustainopt.backend.dashboard.dto.DashboardSummaryResponse;
import com.sustainopt.backend.dashboard.repository.DashboardRepository;
import com.sustainopt.backend.decision.dto.DecisionResponse;
import com.sustainopt.backend.decision.model.DecisionAction;
import com.sustainopt.backend.decision.service.DecisionService;
import com.sustainopt.backend.metrics.entity.SustainabilityMetric;
import com.sustainopt.backend.recommendation.dto.RecommendationResponse;
import com.sustainopt.backend.recommendation.service.RecommendationService;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.MockedStatic;

import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

class DashboardServiceTest {

    private DashboardRepository dashboardRepository;
    private RecommendationService recommendationService;
    private DecisionService decisionService;
    private UserRepository userRepository;
    private DashboardService dashboardService;
    private MockedStatic<SecurityUtils> securityUtilsMock;

    @BeforeEach
    void setUp() {
        dashboardRepository = mock(DashboardRepository.class);
        recommendationService = mock(RecommendationService.class);
        decisionService = mock(DecisionService.class);
        userRepository = mock(UserRepository.class);

        dashboardService = new DashboardService(
                dashboardRepository,
                recommendationService,
                decisionService,
                userRepository
        );

        securityUtilsMock = mockStatic(SecurityUtils.class);
        securityUtilsMock.when(SecurityUtils::getCurrentUserEmail)
                .thenReturn("user@example.com");

        User user = new User();
        user.setEmail("user@example.com");
        user.setOrganizationName("Test Organization");

        when(userRepository.findByEmail("user@example.com"))
                .thenReturn(Optional.of(user));
    }

    @AfterEach
    void tearDown() {
        securityUtilsMock.close();
    }

    @Test
    void returnsDefaultSummaryWhenOrganizationHasNoMetrics() {
        when(dashboardRepository.getTotalMetrics("Test Organization"))
                .thenReturn(0L);
        when(dashboardRepository.getTotalElectricity("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getTotalWater("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getTotalWaste("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getTotalCarbon("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getAverageRenewableEnergy("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getAverageTransportEmission("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository
                .findByOrganizationNameOrderByCreatedAtDesc("Test Organization"))
                .thenReturn(List.of());

        DashboardSummaryResponse response =
                dashboardService.getDashboardSummary();

        assertEquals(0L, response.getTotalMetrics());
        assertEquals(0.0, response.getTotalElectricity());
        assertEquals(0.0, response.getTotalWater());
        assertEquals(0.0, response.getTotalWaste());
        assertEquals(0.0, response.getTotalCarbon());
        assertEquals(0.0, response.getAverageRenewableEnergy());
        assertEquals(0.0, response.getAverageTransportEmission());

        assertEquals(0.0, response.getOverallScore());
        assertEquals("N/A", response.getGrade());
        assertEquals(0.0, response.getShiScore());
        assertEquals("No Data", response.getShiStatus());
        assertEquals(0.0, response.getEstimatedCostSaving());
        assertEquals(false, response.getScenarioAvailable());
        assertEquals("No sustainability metrics available.",
                response.getTopPriorityAction());
        assertEquals(0.0, response.getTopPriorityScore());

        verifyNoInteractions(recommendationService, decisionService);
    }

    @Test
    void buildsSummaryFromLatestMetricAndDecision() {
        SustainabilityMetric metric = new SustainabilityMetric();
        metric.setOrganizationName("Test Organization");

        // A non-null ID is needed because the service passes it to both engines.
        // The entity ID is generated by JPA and has no public setter.
        // Use reflection to simulate a persisted metric.
        org.springframework.test.util.ReflectionTestUtils.setField(
                metric, "id", 42L);

        when(dashboardRepository.getTotalMetrics("Test Organization"))
                .thenReturn(2L);
        when(dashboardRepository.getTotalElectricity("Test Organization"))
                .thenReturn(1500.0);
        when(dashboardRepository.getTotalWater("Test Organization"))
                .thenReturn(2500.0);
        when(dashboardRepository.getTotalWaste("Test Organization"))
                .thenReturn(120.0);
        when(dashboardRepository.getTotalCarbon("Test Organization"))
                .thenReturn(450.0);
        when(dashboardRepository.getAverageRenewableEnergy("Test Organization"))
                .thenReturn(35.0);
        when(dashboardRepository.getAverageTransportEmission("Test Organization"))
                .thenReturn(60.0);
        when(dashboardRepository
                .findByOrganizationNameOrderByCreatedAtDesc("Test Organization"))
                .thenReturn(List.of(metric));

        RecommendationResponse recommendation = new RecommendationResponse();
        recommendation.setOverallScore(82.5);
        recommendation.setGrade("A");
        recommendation.setShiScore(76.0);
        recommendation.setShiStatus("Good");
        recommendation.setEstimatedCostSaving(1250.0);
        recommendation.setScenarioAvailable(true);

        when(recommendationService.generateRecommendations(42L))
                .thenReturn(recommendation);

        DecisionAction action = new DecisionAction();
        action.setActionName("Install renewable energy");
        action.setPriorityScore(91.0);

        DecisionResponse decision = new DecisionResponse();
        decision.setPrioritizedActions(List.of(action));

        when(decisionService.optimizeDecision(42L))
                .thenReturn(decision);

        DashboardSummaryResponse response =
                dashboardService.getDashboardSummary();

        assertEquals(2L, response.getTotalMetrics());
        assertEquals(1500.0, response.getTotalElectricity());
        assertEquals(2500.0, response.getTotalWater());
        assertEquals(120.0, response.getTotalWaste());
        assertEquals(450.0, response.getTotalCarbon());
        assertEquals(35.0, response.getAverageRenewableEnergy());
        assertEquals(60.0, response.getAverageTransportEmission());

        assertEquals(82.5, response.getOverallScore());
        assertEquals("A", response.getGrade());
        assertEquals(76.0, response.getShiScore());
        assertEquals("Good", response.getShiStatus());
        assertEquals(1250.0, response.getEstimatedCostSaving());
        assertTrue(response.getScenarioAvailable());
        assertEquals("Install renewable energy", response.getTopPriorityAction());
        assertEquals(91.0, response.getTopPriorityScore());

        verify(recommendationService).generateRecommendations(42L);
        verify(decisionService).optimizeDecision(42L);
    }

    @Test
    void usesFallbackWhenDecisionHasNoPrioritizedActions() {
        SustainabilityMetric metric = new SustainabilityMetric();
        metric.setOrganizationName("Test Organization");

        org.springframework.test.util.ReflectionTestUtils.setField(
                metric, "id", 42L);

        when(dashboardRepository.getTotalMetrics("Test Organization"))
                .thenReturn(1L);
        when(dashboardRepository.getTotalElectricity("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getTotalWater("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getTotalWaste("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getTotalCarbon("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getAverageRenewableEnergy("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository.getAverageTransportEmission("Test Organization"))
                .thenReturn(0.0);
        when(dashboardRepository
                .findByOrganizationNameOrderByCreatedAtDesc("Test Organization"))
                .thenReturn(List.of(metric));

        RecommendationResponse recommendation = new RecommendationResponse();
        recommendation.setOverallScore(50.0);
        recommendation.setGrade("C");
        recommendation.setShiScore(50.0);
        recommendation.setShiStatus("Moderate");
        recommendation.setEstimatedCostSaving(0.0);
        recommendation.setScenarioAvailable(false);

        when(recommendationService.generateRecommendations(42L))
                .thenReturn(recommendation);

        DecisionResponse decision = new DecisionResponse();
        decision.setPrioritizedActions(List.of());

        when(decisionService.optimizeDecision(42L))
                .thenReturn(decision);

        DashboardSummaryResponse response =
                dashboardService.getDashboardSummary();

        assertEquals("No priority action available.",
                response.getTopPriorityAction());
        assertEquals(0.0, response.getTopPriorityScore());
    }
}