import jsPDF from "jspdf";

export const generateSustainabilityReport = () => {
    const doc = new jsPDF();

    // Title
    doc.setFontSize(22);
    doc.setTextColor(46, 125, 50);
    doc.text("SustainOpt", 20, 25);

    doc.setFontSize(18);
    doc.setTextColor(16, 24, 40);
    doc.text("Sustainability Performance Report", 20, 38);

    doc.setFontSize(11);
    doc.setTextColor(85, 85, 85);
    doc.text(
        "Organization Sustainability Overview",
        20,
        48
    );

    // Divider
    doc.setDrawColor(220, 220, 220);
    doc.line(20, 55, 190, 55);

    // Sustainability Summary
    doc.setFontSize(14);
    doc.setTextColor(16, 24, 40);
    doc.text("Sustainability Summary", 20, 70);

    doc.setFontSize(11);
    doc.text(
        "Sustainability Health Index: 78.4",
        25,
        82
    );

    doc.text(
        "Overall Improvement: +14.6%",
        25,
        92
    );

    doc.text(
        "Metrics Tracked: 12",
        25,
        102
    );

    // Key Metrics
    doc.setFontSize(14);
    doc.text("Key Sustainability Metrics", 20, 120);

    doc.setFontSize(11);

    doc.text(
        "Energy Consumption: 72%",
        25,
        132
    );

    doc.text(
        "Renewable Energy: 42%",
        25,
        142
    );

    doc.text(
        "Water Efficiency: 68%",
        25,
        152
    );

    doc.text(
        "Waste Diversion: 61%",
        25,
        162
    );

    // Recommended Actions
    doc.setFontSize(14);
    doc.text("Recommended Actions", 20, 182);

    doc.setFontSize(11);

    const recommendations = [
        "Increase renewable energy adoption.",
        "Improve water efficiency.",
        "Increase waste diversion.",
        "Continue monitoring carbon performance.",
    ];

    recommendations.forEach((item, index) => {
        doc.text(
            `• ${item}`,
            25,
            194 + index * 10
        );
    });

    // Footer
    doc.setFontSize(9);
    doc.setTextColor(110, 110, 110);

    doc.text(
        "Generated by SustainOpt Sustainability Intelligence Platform",
        20,
        270
    );

    doc.text(
        `Report generated: ${new Date().toLocaleDateString()}`,
        20,
        278
    );

    // Download PDF
    doc.save("SustainOpt-Sustainability-Report.pdf");
};